"""API endpoints and middleware for native desktop bridge verification and per-request proof authentication."""

from datetime import datetime, timezone
import hashlib
import logging
import secrets
import time
from typing import Callable, Optional

from fastapi import APIRouter, HTTPException, Request, Response, status
from pydantic import BaseModel, Field
from starlette.middleware.base import BaseHTTPMiddleware
from starlette.responses import JSONResponse

from pico.api.operator import is_loopback_client
from pico.core.bridge import (
    BRIDGE_PROTOCOL_VERSION,
    BRIDGE_V2_PROTOCOL_VERSION,
    compute_handshake_hmac,
    compute_proof_v2_hmac,
    get_anti_replay_cache,
    get_bridge_secret,
    get_replay_protector,
    parse_timestamp_to_epoch_ns,
)

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/bridge", tags=["Native Desktop Bridge"])


class HandshakeRequest(BaseModel):
    nonce: str = Field(
        ...,
        min_length=16,
        max_length=128,
        description="Fresh cryptographically random nonce generated by the native host.",
    )


class HandshakeResponse(BaseModel):
    status: str = Field(default="verified", description="Handshake outcome indicator.")
    protocol: str = Field(default=BRIDGE_PROTOCOL_VERSION, description="Bridge protocol version.")
    hmac: str = Field(..., description="HMAC-SHA256 signature bound to the launch secret and nonce.")


@router.post(
    "/handshake",
    response_model=HandshakeResponse,
    summary="Complete startup identity challenge for the native desktop host",
)
def bridge_handshake(payload: HandshakeRequest, request: Request) -> HandshakeResponse:
    """Verifies that the request originates from genuine local loopback and computes an HMAC challenge response.

    Invariants:
    1. Restricted strictly to direct local loopback connections.
    2. Fails closed if the backend was not started by a managed supervisor (no bridge secret).
    3. Nonce must be a fresh string of 16-128 characters.
    4. Computes HMAC-SHA256(secret, f"pico-bridge-v1:{nonce}").
    5. Never reveals or logs the underlying secret.
    """
    if not is_loopback_client(request):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Bridge handshake is restricted exclusively to local loopback.",
        )

    if not get_bridge_secret():
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Bridge handshake is not configured on this backend instance.",
        )

    hmac_signature = compute_handshake_hmac(payload.nonce)
    if not hmac_signature:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to compute handshake response.",
        )

    return HandshakeResponse(
        status="verified",
        protocol=BRIDGE_PROTOCOL_VERSION,
        hmac=hmac_signature,
    )


class BridgeAuthMiddleware(BaseHTTPMiddleware):
    """Starlette middleware that enforces ADR 0003 X-Pico-Bridge-Proof: v2 when present.

    Security Invariants:
    1. If `X-Pico-Bridge-Proof` is absent:
       - If the route is a standard web route or handshake, passes through to regular auth/operator handling.
       - If a route explicitly requires native bridge proof, it will fail at route level.
    2. If `X-Pico-Bridge-Proof` is present:
       - Must originate strictly from local loopback (fails closed with 403 Forbidden).
       - Backend must have an active bridge secret (fails closed with 403 Forbidden).
       - Header must strictly parse as: `v2 <timestamp> <nonce> <hmac_hex>`.
       - Nonce must be 16-128 ASCII hex characters.
       - Timestamp must be integer Unix seconds or ISO 8601 string within ±30s clock skew of current UTC time.
       - Anti-replay check: Nonce must not have been seen within the 30s sliding window, and cache must not be saturated.
       - Method: Uppercase HTTP method.
       - Request Target: Exact raw path including query string as transmitted.
       - Body Digest: SHA-256 of exact wire body bytes.
       - HMAC: Constant-time comparison (`secrets.compare_digest`).
       - On success, sets `request.state.bridge_verified = True` and calls next handler.
       - On failure, halts request processing immediately and returns 401 Unauthorized or 403 Forbidden JSONResponse.
    """

    async def dispatch(self, request: Request, call_next: Callable) -> Response:
        header_val = request.headers.get("x-pico-bridge-proof")
        if not header_val:
            # Not a bridge-proof request: pass through to standard handlers
            request.state.bridge_verified = False
            return await call_next(request)

        # 1. Loopback verification
        if not is_loopback_client(request):
            return JSONResponse(
                status_code=status.HTTP_403_FORBIDDEN,
                content={"detail": "Bridge proof is restricted exclusively to local loopback connections."},
            )

        # 2. Bridge secret configuration check
        secret = get_bridge_secret()
        if not secret:
            return JSONResponse(
                status_code=status.HTTP_403_FORBIDDEN,
                content={"detail": "Native bridge authentication is not configured on this backend instance."},
            )

        # 3. Header structure parsing: "v2 <timestamp> <nonce> <hmac_hex>"
        parts = header_val.strip().split()
        if len(parts) != 4 or parts[0] != BRIDGE_V2_PROTOCOL_VERSION:
            return JSONResponse(
                status_code=status.HTTP_401_UNAUTHORIZED,
                content={"detail": "Malformed X-Pico-Bridge-Proof header format. Expected 'v2 <timestamp> <nonce> <hmac>'."},
            )

        version_part, timestamp_part, nonce_part, hmac_part = parts

        # Validate nonce characters and length (16 to 128 chars)
        if not (16 <= len(nonce_part) <= 128) or not all(c in "0123456789abcdefABCDEF" for c in nonce_part):
            return JSONResponse(
                status_code=status.HTTP_401_UNAUTHORIZED,
                content={"detail": "Invalid bridge proof nonce: must be 16-128 hex characters."},
            )

        # 4. Parse timestamp into integer nanoseconds
        req_ts_ns = parse_timestamp_to_epoch_ns(timestamp_part)
        if req_ts_ns is None:
            return JSONResponse(
                status_code=status.HTTP_401_UNAUTHORIZED,
                content={"detail": "Malformed timestamp in bridge proof header."},
            )

        # 5. Read and digest raw body
        body_bytes = await request.body()
        body_digest = hashlib.sha256(body_bytes).hexdigest()

        # 6. Construct request target (exact raw path + raw query string)
        raw_path = request.scope.get("raw_path")
        if raw_path:
            path_part = raw_path.decode("latin-1")
        else:
            path_part = request.url.path

        raw_qs = request.scope.get("query_string")
        if raw_qs:
            qs_part = raw_qs.decode("latin-1")
            request_target = f"{path_part}?{qs_part}"
        elif request.url.query:
            request_target = f"{path_part}?{request.url.query}"
        else:
            request_target = path_part

        # 7. Compute expected HMAC
        expected_hmac = compute_proof_v2_hmac(
            secret=secret,
            version=version_part,
            timestamp=timestamp_part,
            nonce=nonce_part,
            method=request.method.upper(),
            request_target=request_target,
            body_digest=body_digest,
        )

        # 8. Constant-time comparison: HMAC MUST be verified BEFORE consuming nonce
        if not secrets.compare_digest(expected_hmac.lower(), hmac_part.lower()):
            return JSONResponse(
                status_code=status.HTTP_401_UNAUTHORIZED,
                content={"detail": "Bridge proof HMAC signature verification failed."},
            )

        # 9. Atomic timestamp freshness validation and nonce consumption
        protector = get_replay_protector()
        accepted, reason = protector.validate_and_consume(nonce_part, req_ts_ns)
        if not accepted:
            status_code = (
                status.HTTP_403_FORBIDDEN
                if ("saturated" in reason or "Clock unavailable" in reason)
                else status.HTTP_401_UNAUTHORIZED
            )
            return JSONResponse(
                status_code=status_code,
                content={"detail": reason},
            )

        # Mark request as bridge verified
        request.state.bridge_verified = True

        # Continue request chain
        return await call_next(request)
